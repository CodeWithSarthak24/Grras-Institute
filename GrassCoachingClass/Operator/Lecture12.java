package GrassCoachingClass.Operator;

// Shift operator Left shift (<<)
// formula : a<<n = a × 2 ^ n

public class Lecture12 {
    public static void main(String[] args) {

        int x = 5;
        System.out.println(x << 5);


       // Shift operator right shift (>>)
        // Formula : a >> n = a / 2ⁿ

        int z = 21;
        System.out.println(z >> 2);

    }
}
